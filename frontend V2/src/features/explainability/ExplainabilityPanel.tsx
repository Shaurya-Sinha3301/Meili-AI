import { ExplanationCard } from './ExplanationCard';
import { ApprovalCard } from './ApprovalCard';
import { Card, CardHeader, CardTitle, CardMeta } from '../../components/ui/Card';
import { Badge } from '../../components/ui/Badge';
import { useExplainability } from '../../hooks/useExplainability';
import type { ExplanationStep, Constraint } from '../../lib/types';

const CONSTRAINTS: Constraint[] = [
  { id: 'c1', label: 'Budget limit', value: '€8,500 total', type: 'hard' },
  { id: 'c2', label: 'Max layover', value: '2 hours', type: 'hard' },
  { id: 'c3', label: 'Hotel check-in', value: 'After 14:00', type: 'hard' },
  { id: 'c4', label: 'Preferred airlines', value: 'BA, Lufthansa', type: 'soft' },
  { id: 'c5', label: 'Preferred hotel tier', value: '4–5 star', type: 'soft' },
  { id: 'c6', label: 'Activity density', value: 'Max 2 per half-day', type: 'soft' },
  { id: 'c7', label: 'Meal preference', value: 'Local cuisine', type: 'soft' },
  { id: 'c8', label: 'Airport buffer', value: 'Min 2h before departure', type: 'hard' },
];

